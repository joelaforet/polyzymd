def _estimate_solvation_box(topology: object, *, padding_nm: float) -> SolvationBoxEstimate:
    """Estimate padded cube dimensions and an upper-bound water count.

    Parameters
    ----------
    topology : object
        OpenFF topology-like object with finite coordinates.
    padding_nm : float
        Solvent padding in nanometers.

    Returns
    -------
    SolvationBoxEstimate
        Coordinate span, padded box lengths, volume, and estimated water count.
    """
    positions_nm = _topology_positions_nm(topology)
    solute_span = np.ptp(positions_nm, axis=0)
    padded_lengths = solute_span + 2.0 * padding_nm
    volume_nm3 = float(np.prod(padded_lengths))
    estimated_waters = int(math.ceil(volume_nm3 * WATER_NUMBER_DENSITY_NM3))
    return SolvationBoxEstimate(
        solute_span_nm=tuple(float(value) for value in solute_span),
        padded_lengths_nm=tuple(float(value) for value in padded_lengths),
        volume_nm3=volume_nm3,
        estimated_waters=estimated_waters,
    )


def _topology_positions_nm(topology: object) -> np.ndarray:
    """Return topology coordinates as a finite ``(n_atoms, 3)`` nanometer array."""
    get_positions = getattr(topology, "get_positions", None)
    positions = get_positions() if callable(get_positions) else None
    if positions is None:
        positions = _stack_molecule_conformers_nm(topology)
    elif hasattr(positions, "m_as"):
        positions = positions.m_as("nanometer")
    array = np.asarray(positions, dtype=float)
    if array.ndim != 2 or array.shape[1] != 3:
        raise ValueError(f"Topology positions must have shape (n_atoms, 3), got {array.shape}")
    if array.shape[0] == 0:
        raise ValueError("Topology positions are empty; cannot estimate solvation box")
    if not bool(np.all(np.isfinite(array))):
        raise ValueError("Topology positions contain non-finite coordinates")
    return array


def _stack_molecule_conformers_nm(topology: object) -> np.ndarray:
    """Stack first conformers from topology molecules when direct positions are absent."""
    arrays: list[np.ndarray] = []
    for molecule in getattr(topology, "molecules", ()):  # pragma: no branch - test doubles vary
        conformers = getattr(molecule, "conformers", ())
        if not conformers:
            continue
        conformer = conformers[0]
        if hasattr(conformer, "m_as"):
            arrays.append(np.asarray(conformer.m_as("nanometer"), dtype=float))
        else:
            arrays.append(np.asarray(conformer, dtype=float))
    if not arrays:
        raise ValueError("Topology has no positions or molecule conformers for box estimation")
    return np.vstack(arrays)


def _print_solvation_estimate(estimate: SolvationBoxEstimate) -> None:
    """Print the pre-PACKMOL solvation estimate."""
    print(
        "[conjugation-gpu-smoke] Pre-PACKMOL estimate: "
        f"span_nm={_format_triplet(estimate.solute_span_nm)}, "
        f"padded_lengths_nm={_format_triplet(estimate.padded_lengths_nm)}, "
        f"volume={estimate.volume_nm3:.2f} nm^3, "
        f"estimated_waters<={estimate.estimated_waters}"
    )


def _guard_solvation_box_estimate(
    estimate: SolvationBoxEstimate,
    limits: SolvationSmokeLimits,
) -> None:
    """Fail before PACKMOL when the estimated smoke system is too large."""
    failures: list[str] = []
    max_span = max(estimate.solute_span_nm)
    max_box_edge = max(estimate.padded_lengths_nm)
    if max_span > limits.max_solute_span_nm:
        failures.append(f"solute span {max_span:.3f} nm > {limits.max_solute_span_nm:.3f} nm")
    if max_box_edge > limits.max_box_edge_nm:
        failures.append(f"box edge {max_box_edge:.3f} nm > {limits.max_box_edge_nm:.3f} nm")
    if estimate.estimated_waters > limits.max_waters:
        failures.append(f"estimated waters {estimate.estimated_waters} > {limits.max_waters}")
    if failures:
        pytest.fail(
            "Pre-PACKMOL solvation estimate exceeds smoke limits: "
            + "; ".join(failures)
            + ". Reduce the fixture size/padding or override the guard env vars if intentional."
        )


def _print_solvated_topology_summary(topology: object, solvent_builder: object) -> None:
    """Print immediate post-PACKMOL topology and solvent counts."""
    counts = getattr(solvent_builder, "solvation_counts", None)
    water = "unknown" if counts is None else str(counts.water)
    na = "unknown" if counts is None else str(counts.na)
    cl = "unknown" if counts is None else str(counts.cl)
    print(
        "[conjugation-gpu-smoke] Post-PACKMOL topology: "
        f"atoms={int(topology.n_atoms)}, "
        f"molecules={int(topology.n_molecules)}, "
        f"water={water}, Na={na}, Cl={cl}"
    )


def _guard_solvated_topology_size(
    topology: object,
    solvent_builder: object | None,
    limits: SolvationSmokeLimits,
) -> None:
    """Fail immediately after PACKMOL when topology size exceeds smoke limits."""
    failures: list[str] = []
    atom_count = int(topology.n_atoms)
    molecule_count = int(topology.n_molecules)
    counts = None if solvent_builder is None else getattr(solvent_builder, "solvation_counts", None)
    if atom_count > limits.max_atoms:
        failures.append(f"atoms {atom_count} > {limits.max_atoms}")
    if molecule_count > limits.max_molecules:
        failures.append(f"molecules {molecule_count} > {limits.max_molecules}")
    if counts is not None and counts.water > limits.max_waters:
        failures.append(f"waters {counts.water} > {limits.max_waters}")
    if failures:
        pytest.fail(
            "Solvated topology exceeds smoke limits: "
            + "; ".join(failures)
            + ". This would make Interchange or CUDA diagnostics too slow for the smoke."
        )


def _format_triplet(values: tuple[float, float, float]) -> str:
    """Format a numeric triplet for compact stage diagnostics."""
    return "(" + ", ".join(f"{value:.3f}" for value in values) + ")"


def _int_env(name: str, *, default: int) -> int:
    """Read a non-negative integer environment override."""
    value = os.environ.get(name)
    if value is None or value == "":
        return default
    parsed = int(value)
    if parsed < 0:
        raise ValueError(f"{name} must be non-negative, got {parsed}")
    return parsed


