def _timeout_seconds_env(name: str, *, default: float) -> float | None:
    """Read a timeout override, returning ``None`` when disabled with zero."""
    value = os.environ.get(name)
    if value is None or value == "":
        parsed = default
    else:
        parsed = float(value)
    if parsed < 0.0:
        raise ValueError(f"{name} must be non-negative, got {parsed}")
    if parsed == 0.0:
        return None
    return parsed
