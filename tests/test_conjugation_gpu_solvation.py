@pytest.mark.slow
@pytest.mark.conjugation_stack
def test_opt_in_cuda_required_for_conjugation_solvation_full_build(tmp_path: Path):
    """Require CUDA and prove a solvated system can create a finite CUDA state.

    This expensive test is intentionally opt-in and must not fall back to CPU.
    The linked conjugate input is generated by default and must complete the
    direct link, restrained vacuum minimization, and short vacuum MD before the
    relaxed conformer is solvated through the OpenFF/PACKMOL/Interchange path.
    """
    openmm, openmm_unit, platform = _require_gpu_solvation_stack_or_skip()
    artifact_dir = tmp_path / "gpu-solvation"
    artifact_dir.mkdir(parents=True, exist_ok=True)
    limits = _solvation_smoke_limits_from_env()
    padding_nm = _float_env(GPU_PADDING_ENV_VAR, default=DEFAULT_GPU_PADDING_NM)
    print(
        "[conjugation-gpu-smoke] Limits: "
        f"padding={padding_nm:.3f} nm, max_span={limits.max_solute_span_nm:.3f} nm, "
        f"max_box_edge={limits.max_box_edge_nm:.3f} nm, max_waters={limits.max_waters}, "
        f"max_atoms={limits.max_atoms}, max_molecules={limits.max_molecules}"
    )

    with _timed_stage(
        "direct artifact generation",
        timeout_s=_timeout_seconds_env(GPU_DIRECT_TIMEOUT_ENV_VAR, default=300.0),
    ):
        direct_result = _direct_artifact_from_env_or_generate(artifact_dir)
    assert direct_result.linked_pdb_path.exists()
    assert direct_result.linked_bond.conect_present is True
    assert direct_result.topology is not None
    assert direct_result.charge_template is not None
    expected_restrained_atom_count = len(_all_heavy_atom_indices(direct_result.linked_pdb_path))
    protein_heavy_atom_count = len(_protein_heavy_atom_indices(direct_result.linked_pdb_path))
    assert expected_restrained_atom_count > protein_heavy_atom_count

    from openff.interchange.interop.openmm._positions import to_openmm_positions

    from polyzymd.builders.conjugation.pablo.parameterization import (
        create_interchange_from_openff_topology,
        set_topology_positions_from_pdb,
    )
    from polyzymd.builders.conjugation._relaxation import VacuumSmokeSettings, run_restrained_vacuum_smoke
    from polyzymd.builders.solvent import SolventBuilder, SolventComposition
    from polyzymd.data.solvent_molecules import get_solvent_molecule

    with _timed_stage("vacuum parameterization"):
        vacuum_parameterization = create_interchange_from_openff_topology(
            direct_result.topology,
            charge_from_molecules=(direct_result.charge_template,),
            success_diagnostic="Direct linked conjugate was parameterized before vacuum relaxation",
            failure_subject="direct linked conjugate topology",
        )
    assert vacuum_parameterization.interchange is not None

    with _timed_stage("restrained vacuum EM and MD"):
        vacuum_result = run_restrained_vacuum_smoke(
            vacuum_parameterization.interchange,
            artifact_dir / "vacuum-relaxation",
            protein_heavy_atom_indices=None,
            settings=VacuumSmokeSettings(
                minimization_max_iterations=_int_env(
                    GPU_MINIMIZATION_ITERS_ENV_VAR,
                    default=DEFAULT_GPU_MINIMIZATION_ITERS,
                ),
                nvt_steps=_positive_int_env(GPU_NVT_STEPS_ENV_VAR, default=2),
                platform_name="CUDA",
            ),
        )
    assert vacuum_result.success
    assert vacuum_result.equilibrated_pdb_path is not None
    assert vacuum_result.equilibrated_pdb_path.exists()
    assert vacuum_result.nvt_steps > 0, "Restrained vacuum MD must run before solvation"
    assert vacuum_result.restrained_atom_count == expected_restrained_atom_count

    with _timed_stage("relaxed position transfer"):
        relaxed_topology = set_topology_positions_from_pdb(
            direct_result.topology,
            vacuum_result.equilibrated_pdb_path,
        )

    with _timed_stage("solvation box and count setup"):
        estimate = _estimate_solvation_box(relaxed_topology, padding_nm=padding_nm)
        _print_solvation_estimate(estimate)
        _guard_solvation_box_estimate(estimate, limits)

    solvent_builder = SolventBuilder()
    with _timed_stage(
        "PACKMOL solvation",
        timeout_s=_timeout_seconds_env(GPU_PACKMOL_TIMEOUT_ENV_VAR, default=180.0),
    ):
        solvated_topology = solvent_builder.solvate(
            relaxed_topology,
            composition=SolventComposition(
                water_model="tip3p",
                nacl_concentration=0.0,
                neutralize=False,
            ),
            padding=padding_nm,
            box_shape="cube",
            tolerance=2.0,
        )
    _print_solvated_topology_summary(solvated_topology, solvent_builder)
    _guard_solvated_topology_size(solvated_topology, solvent_builder, limits)
    solvated_pdb = artifact_dir / "solvated_system.pdb"
    solvated_topology.to_file(str(solvated_pdb), keep_ids=True)

    with _timed_stage(
        "solvated Interchange creation",
        timeout_s=_timeout_seconds_env(GPU_INTERCHANGE_TIMEOUT_ENV_VAR, default=300.0),
    ):
        solvated_parameterization = create_interchange_from_openff_topology(
            solvated_topology,
            charge_from_molecules=(direct_result.charge_template, get_solvent_molecule("tip3p")),
            success_diagnostic="Relaxed direct conjugate was solvated and parameterized",
            failure_subject="solvated direct conjugate topology",
        )
    assert solvated_parameterization.interchange is not None

    with _timed_stage(
        "OpenMM CUDA system/context/energy/force evaluation",
        timeout_s=_timeout_seconds_env(GPU_CUDA_TIMEOUT_ENV_VAR, default=120.0),
    ):
        system = solvated_parameterization.interchange.to_openmm_system()
        system_xml = artifact_dir / "system.xml"
        system_xml.write_text(openmm.XmlSerializer.serialize(system), encoding="utf-8")
        positions = to_openmm_positions(
            solvated_parameterization.interchange,
            include_virtual_sites=True,
        )

        integrator = openmm.VerletIntegrator(0.001 * openmm_unit.picoseconds)
        context = openmm.Context(system, integrator, platform, {"CudaPrecision": "mixed"})
        context.setPositions(positions)
        state = context.getState(getEnergy=True, getForces=True)
        energy = state.getPotentialEnergy().value_in_unit(openmm_unit.kilojoule_per_mole)
        forces = state.getForces(asNumpy=True).value_in_unit(
            openmm_unit.kilojoule_per_mole / openmm_unit.nanometer
        )
        context_platform = context.getPlatform().getName()
        del context
        del integrator

    assert context_platform == "CUDA"
    assert solvated_pdb.exists()
    assert system_xml.exists()
    assert math.isfinite(float(energy))
    assert np.all(np.isfinite(forces))


