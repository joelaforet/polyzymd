def _require_gpu_solvation_stack_or_skip():
    """Return OpenMM modules and a validated CUDA platform or skip."""
    if os.environ.get(GPU_ENV_VAR) != "1":
        pytest.skip(f"Set {GPU_ENV_VAR}=1 to run the CUDA solvation smoke")
    if shutil.which("packmol") is None:
        pytest.skip("Packmol binary is not available on PATH")

    pytest.importorskip("polymerist", exc_type=ImportError)
    pytest.importorskip("openff.toolkit")
    pytest.importorskip("openff.interchange")
    pytest.importorskip("rdkit")

    openmm = pytest.importorskip("openmm")
    from openmm import unit as openmm_unit

    try:
        platform = openmm.Platform.getPlatformByName("CUDA")
    except Exception as exc:  # noqa: BLE001 - OpenMM platform lookup varies by installation
        pytest.skip(f"CUDA platform is required and no CPU fallback is allowed: {exc}")

    probe_system = openmm.System()
    probe_system.addParticle(39.9)
    probe_integrator = openmm.VerletIntegrator(0.001 * openmm_unit.picoseconds)
    try:
        probe_context = openmm.Context(probe_system, probe_integrator, platform)
        probe_context.setPositions([[0.0, 0.0, 0.0]] * openmm_unit.nanometer)
        probe_context.getState(getEnergy=True)
    except Exception as exc:  # noqa: BLE001 - CUDA resource failures vary by cluster state
        pytest.skip(f"CUDA platform is registered but unusable; no CPU fallback is allowed: {exc}")
    finally:
        if "probe_context" in locals():
            del probe_context
        del probe_integrator

    return openmm, openmm_unit, platform


def _direct_artifact_from_env_or_generate(artifact_dir: Path):
    """Return or generate the direct linked conjugate artifact for the GPU smoke."""
    value = os.environ.get("POLYZYMD_CONJUGATION_LINKED_PDB")
    if value:
        pytest.fail(
            "POLYZYMD_CONJUGATION_LINKED_PDB is no longer accepted for the GPU solvation smoke. "
            "The test must generate a direct artifact with an OpenFF topology and charge template "
            "so it can run vacuum relaxation before solvation."
        )

    from tests.test_conjugation_integrated_direct_smoke import build_direct_smoke_artifact

    return build_direct_smoke_artifact(artifact_dir / "direct-input")


def _protein_heavy_atom_indices(pdb_path: Path) -> tuple[int, ...]:
    """Return zero-based chain-A non-hydrogen atom indices from a PDB artifact."""
    indices: list[int] = []
    for atom in _heavy_atom_records(pdb_path):
        if atom.atom_index is None:
            continue
        if atom.chain_id == "A":
            indices.append(atom.atom_index)
    if not indices:
        pytest.fail(f"No chain-A heavy atoms were found for restraints in {pdb_path}")
    return tuple(indices)


def _all_heavy_atom_indices(pdb_path: Path) -> tuple[int, ...]:
    """Return zero-based non-hydrogen atom indices from a PDB artifact."""
    indices = tuple(
        atom.atom_index for atom in _heavy_atom_records(pdb_path) if atom.atom_index is not None
    )
    if not indices:
        pytest.fail(f"No heavy atoms were found for restraints in {pdb_path}")
    return indices


def _heavy_atom_records(pdb_path: Path) -> Iterator[Any]:
    """Yield non-hydrogen PDB atom records from a linked conjugate artifact."""
    from polyzymd.builders.conjugation._linkage import parse_pdb_atom_records

    for atom in parse_pdb_atom_records(pdb_path):
        element = (atom.element or "").upper()
        if element != "H" and not atom.atom_name.upper().startswith("H"):
            yield atom


@contextmanager
def _timed_stage(stage_name: str, *, timeout_s: float | None = None) -> Iterator[None]:
    """Print wall-time diagnostics and optionally fail on a stage timeout.

    Parameters
    ----------
    stage_name : str
        Human-readable stage name shown in pytest ``-s`` output.
    timeout_s : float or None, optional
        Wall-time timeout in seconds. ``None`` disables the alarm.
    """
    start = time.perf_counter()
    timeout_label = "none" if timeout_s is None else f"{timeout_s:.1f} s"
    print(f"[conjugation-gpu-smoke] START {stage_name} (timeout={timeout_label})")
    old_handler = None
    old_timer = None
    timer_enabled = timeout_s is not None and hasattr(signal, "SIGALRM")

    if timer_enabled:
        old_handler = signal.getsignal(signal.SIGALRM)

        def _raise_timeout(signum: int, frame: object) -> None:
            del signum, frame
            raise TimeoutError(
                f"Stage '{stage_name}' exceeded {timeout_s:.1f} seconds. "
                "Increase the corresponding POLYZYMD_CONJUGATION_GPU_SOLVATION_*_TIMEOUT_S "
                "environment variable only after checking the stage diagnostics."
            )

        signal.signal(signal.SIGALRM, _raise_timeout)
        old_timer = signal.setitimer(signal.ITIMER_REAL, float(timeout_s))

    try:
        yield
    except TimeoutError as exc:
        elapsed = time.perf_counter() - start
        print(f"[conjugation-gpu-smoke] TIMEOUT {stage_name} after {elapsed:.2f} s: {exc}")
        pytest.fail(str(exc))
    finally:
        if timer_enabled:
            signal.setitimer(signal.ITIMER_REAL, 0.0)
            if old_timer is not None and old_timer[0] > 0.0:
                remaining = max(old_timer[0] - (time.perf_counter() - start), 0.0)
                signal.setitimer(signal.ITIMER_REAL, remaining, old_timer[1])
            signal.signal(signal.SIGALRM, old_handler)
        elapsed = time.perf_counter() - start
        print(f"[conjugation-gpu-smoke] END {stage_name} ({elapsed:.2f} s)")


