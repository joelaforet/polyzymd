"""Scaffold generator for new analysis plugins.

Creates the minimal file set needed for a new analysis plugin:
- ``src/polyzymd/analyses/<name>/__init__.py``  — plugin class with compute,
  aggregate, comparison, and plotting methods
- ``tests/analyses/plugins/test_<name>.py``  — smoke tests covering discovery,
  compute, aggregate, metrics, and plotting

Two styles are available via the ``--style`` flag:

- **dict** (default) — Plain dicts for results, no Pydantic result models.
  Simplest starting point for new contributors.
- **pydantic** — Typed Pydantic result models (``ReplicateResult``,
  ``AggregatedResult``) with ``AggregatedResultClass``.  Better for complex
  analyses that need validation and IDE autocomplete.

Per-analysis plot settings (``_plot_settings.py``) are **not** generated by
default.  They are optional and only needed if you want per-analysis
customization fields accessible via ``plot_settings.<name>`` in
``comparison.yaml``.  See existing plugins like ``rmsf/_plot_settings.py``
for examples.

Usage::

    polyzymd new-analysis my_analysis
    polyzymd new-analysis my_analysis --style pydantic
    polyzymd new-analysis my_analysis --dry-run
    polyzymd new-analysis my_analysis --force
"""

from __future__ import annotations

import keyword
import re
from pathlib import Path

# ---------------------------------------------------------------------------
# Name helpers
# ---------------------------------------------------------------------------

_NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")

_RESERVED_NAMES = frozenset(
    {
        "base",
        "cli",
        "config",
        "discovery",
        "orchestrator",
        "runner",
        "shared",
        "stats",
    }
)

VALID_STYLES = ("dict", "pydantic")


def validate_name(name: str, *, check_existing: bool = True) -> str | None:
    """Return an error message if *name* is not a valid plugin name, else None.

    Parameters
    ----------
    name : str
        Proposed plugin name in snake_case.
    check_existing : bool
        If True, also reject names that collide with already-registered
        analysis plugins or their aliases.
    """
    if not _NAME_RE.match(name):
        return (
            f"'{name}' is not a valid plugin name. Use lowercase snake_case (e.g. 'my_analysis')."
        )
    if keyword.iskeyword(name):
        return f"'{name}' is a Python keyword."
    if name in _RESERVED_NAMES:
        return f"'{name}' is reserved for framework infrastructure."
    if check_existing:
        try:
            from polyzymd.analyses.discovery import list_all_names

            if name in list_all_names():
                return f"'{name}' already exists as a registered analysis plugin."
        except ImportError:
            pass  # Discovery module not available (e.g. minimal install)
    return None


def validate_class_name(class_name: str) -> str | None:
    """Return an error message if *class_name* is not a valid class prefix, else None.

    Parameters
    ----------
    class_name : str
        Proposed PascalCase class prefix (e.g. ``SolventShell``).
        Will be used as ``<class_name>Analysis``, ``<class_name>Settings``, etc.
    """
    if not class_name.isidentifier():
        return (
            f"'{class_name}' is not a valid Python identifier. "
            "Use PascalCase (e.g. 'SolventShell')."
        )
    if keyword.iskeyword(class_name):
        return f"'{class_name}' is a Python keyword and cannot be used as a class name."
    if not class_name[0].isupper():
        return f"'{class_name}' should start with an uppercase letter (PascalCase convention)."
    return None


def to_pascal_case(snake: str) -> str:
    """Convert ``snake_case`` to ``PascalCase``."""
    return "".join(part.capitalize() for part in snake.split("_"))


