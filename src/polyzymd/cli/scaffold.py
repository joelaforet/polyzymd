_PLUGIN_TEMPLATES = {
    "dict": _plugin_init_dict,
    "pydantic": _plugin_init_pydantic,
}

_TEST_TEMPLATES = {
    "dict": _test_file_dict,
    "pydantic": _test_file_pydantic,
}


# ---------------------------------------------------------------------------
# File generation
# ---------------------------------------------------------------------------


def generate_scaffold(
    name: str,
    project_root: Path,
    *,
    class_name: str | None = None,
    style: str = "dict",
    force: bool = False,
    dry_run: bool = False,
) -> list[Path]:
    """Create scaffold files for a new analysis plugin.

    Parameters
    ----------
    name : str
        Plugin name in snake_case (e.g. ``"solvent_shell"``).
    project_root : Path
        Repository root directory (contains ``src/`` and ``tests/``).
    class_name : str or None
        PascalCase class prefix.  Auto-derived from *name* if not given.
    style : str
        ``"dict"`` (default) for plain-dict results, or ``"pydantic"``
        for typed Pydantic result models.
    force : bool
        Overwrite existing files.
    dry_run : bool
        Print paths without writing files.

    Returns
    -------
    list[Path]
        Paths of created (or would-be-created) files.
    """
    # Validate style
    if style not in VALID_STYLES:
        raise ValueError(f"Invalid style '{style}'. Choose from: {', '.join(VALID_STYLES)}")

    # Validate the plugin name — always check for name collisions with
    # existing plugins/aliases, even with --force.  The --force flag only
    # allows overwriting *files*, not reusing a registered plugin name.
    name_error = validate_name(name, check_existing=True)
    if name_error:
        raise ValueError(name_error)

    cls = class_name or to_pascal_case(name)

    # Validate the class name (whether user-supplied or auto-derived)
    cls_error = validate_class_name(cls)
    if cls_error:
        raise ValueError(cls_error)

    analyses_dir = project_root / "src" / "polyzymd" / "analyses" / name
    tests_dir = project_root / "tests"

    plugin_template = _PLUGIN_TEMPLATES[style]
    test_template = _TEST_TEMPLATES[style]

    files: dict[Path, str] = {
        analyses_dir / "__init__.py": plugin_template(name, cls),
        tests_dir / "analyses" / "plugins" / f"test_{name}.py": test_template(name, cls),
    }

    created: list[Path] = []
    for path, content in files.items():
        if path.exists() and not force:
            raise FileExistsError(f"{path} already exists. Use --force to overwrite.")
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        created.append(path)

    return created
